<h2>12. Yargı Paketi''nin Amacı Nedir?</h2>
<p>Paketin temel hedefi, davaların esasına geçilmeden önce yıllarca süren usuli tıkanıklıkları azaltmak. Uzayan yargılama süreleri hem vatandaşlar hem de iş dünyası açısından ciddi bir hak kaybı ve öngörülemezlik kaynağı olarak görülüyor. Bu doğrultuda Kanun; medeni usul, ceza muhakemesi, icra-iflas hukuku, noterlik işlemleri ve tebligat süreçlerinde çok sayıda değişiklik getiriyor.</p>

