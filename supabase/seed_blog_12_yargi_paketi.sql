<h3>1. TCK m. 158/4 — IBAN ve Hesap Bilgisi Mağdurlarına Ceza İndirimi</h3>
<p>Kanunun en çok konuşulan hükümlerinden biri, Türk Ceza Kanunu''nun 158. maddesine eklenen dördüncü fıkra. Buna göre, nitelikli dolandırıcılık suçuna iştiraki yalnızca banka kartı, IBAN veya hesap bilgisi vermekten ibaret olan kişilerin cezası <strong>yarı oranında indiriliyor</strong>. Bu düzenleme, özellikle bilmeden veya kandırılarak hesabını dolandırıcılık amacıyla kullandıran ve kamuoyunda “IBAN mağduru” olarak anılan kişileri, asıl faillerle aynı ağırlıkta cezalandırılmaktan koruma amacı taşıyor.</p>

<h3>2. Hükmün Açıklanmasının Geri Bırakılması (HAGB) Düzenlemesi</h3>
<p>Ceza Muhakemesi Kanunu''nun 231. maddesinde düzenlenen HAGB (hükmün açıklanmasının geri bırakılması) müessesesi yeniden ele alındı. Yapılan değişiklikle HAGB, <strong>işkence ve kötü muamele suçlarında artık uygulanmayacak</strong>.</p>

